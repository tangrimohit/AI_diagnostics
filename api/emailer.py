"""Outbound email for AKARI (feedback confirmations + nudges).

Provider-abstracted and fully env-driven so a future server / domain is a
.env change, not a code edit. Defaults are placeholders but nothing
here hardcodes that beyond the default string.

Config (all via .env / os.environ):
  AKARI_EMAIL_ENABLED     "true" to actually send; anything else = dry-run.
  AKARI_EMAIL_PROVIDER    "resend" (only provider implemented today).
  RESEND_API_KEY          Resend API key (required to send).
  AKARI_EMAIL_FROM        From header, e.g. 'AKARI <akari@your-domain>'.
  AKARI_EMAIL_REPLY_TO    Optional Reply-To address.
  AKARI_EMAIL_BCC         Optional BCC (e.g. an admin copy). Comma-separated ok.
  AKARI_PUBLIC_BASE_URL   Base URL for links in emails (set per deployment).

Dry-run mode (disabled or no key): the rendered email is appended to
data/email-dryrun.log and the send returns {"status": "dry_run"}. This lets the
whole flow be built and tested before the Resend key exists.

Opsec: emails are opaque AKARI branding. No model names, framework names, or
architecture hints. The disclaimer below mirrors the in-app one.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import httpx

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def _dryrun_log_path() -> Path:
    """Honor AKARI_DATA_DIR (same resolution as db.data_dir) so the dry-run log
    lands beside the real stores, not a hardcoded ./data."""
    raw = os.environ.get("AKARI_DATA_DIR", "./data")
    p = Path(raw)
    if not p.is_absolute():
        p = (PROJECT_ROOT / p).resolve()
    return p / "email-dryrun.log"

DISCLAIMER_TEXT = (
    "This diagnosis is generated by AKARI based on documented failure patterns "
    "and technical references. Recommendations are for technician guidance only. "
    "Actual repair times, costs, and parts availability vary by region, model "
    "revision, and individual case. Always verify with current service "
    "documentation and authorized parts catalogs before performing repairs. "
    "AKARI is a decision-support tool, not a substitute for qualified technician "
    "judgment."
)


# ---------------- config ----------------

def _enabled() -> bool:
    return os.environ.get("AKARI_EMAIL_ENABLED", "").strip().lower() in ("1", "true", "yes", "on")


def _provider() -> str:
    return os.environ.get("AKARI_EMAIL_PROVIDER", "resend").strip().lower()


def _from_addr() -> str:
    return os.environ.get("AKARI_EMAIL_FROM", "AKARI <akari@your-domain>").strip()


def _reply_to() -> Optional[str]:
    v = os.environ.get("AKARI_EMAIL_REPLY_TO", "").strip()
    return v or None


def _bcc() -> list[str]:
    raw = os.environ.get("AKARI_EMAIL_BCC", "").strip()
    return [a.strip() for a in raw.split(",") if a.strip()]


def base_url() -> str:
    return os.environ.get("AKARI_PUBLIC_BASE_URL", "https://akari.your-domain").strip().rstrip("/")


def is_configured() -> bool:
    """True if we can actually send (enabled + provider creds present)."""
    if not _enabled():
        return False
    if _provider() == "resend":
        return bool(os.environ.get("RESEND_API_KEY", "").strip())
    return False


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------- send ----------------

def send(to: str, subject: str, html: str, text: Optional[str] = None) -> dict[str, Any]:
    """Send one email. Returns {status, id?, error?}.

    status: "sent" | "dry_run" | "failed". Never raises (callers fire-and-forget).
    """
    if not to or "@" not in to:
        return {"status": "failed", "error": "no valid recipient"}

    if not is_configured():
        _dry_run_dump(to, subject, html, text)
        return {"status": "dry_run"}

    try:
        if _provider() == "resend":
            return _send_resend(to, subject, html, text)
        return {"status": "failed", "error": f"unknown provider {_provider()}"}
    except Exception as e:  # never let email break the caller
        return {"status": "failed", "error": str(e)[:300]}


def _send_resend(to: str, subject: str, html: str, text: Optional[str]) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "from": _from_addr(),
        "to": [to],
        "subject": subject,
        "html": html,
    }
    if text:
        payload["text"] = text
    if _reply_to():
        payload["reply_to"] = _reply_to()
    if _bcc():
        payload["bcc"] = _bcc()
    headers = {"Authorization": f"Bearer {os.environ['RESEND_API_KEY'].strip()}"}
    with httpx.Client(timeout=12.0) as client:
        r = client.post("https://api.resend.com/emails", json=payload, headers=headers)
    if r.status_code in (200, 201):
        return {"status": "sent", "id": (r.json() or {}).get("id")}
    return {"status": "failed", "error": f"resend {r.status_code}: {r.text[:200]}"}


def _dry_run_dump(to: str, subject: str, html: str, text: Optional[str]) -> None:
    try:
        log_path = _dryrun_log_path()
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with log_path.open("a", encoding="utf-8") as f:
            f.write(f"\n===== {_now_iso()}  TO: {to} =====\n")
            f.write(f"SUBJECT: {subject}\n")
            f.write("---- text ----\n")
            f.write((text or "(no text part)") + "\n")
    except Exception:
        pass


# ---------------- templates ----------------

def _esc(s: Any) -> str:
    s = "" if s is None else str(s)
    return (
        s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _short_date(ts: Optional[str]) -> str:
    if not ts:
        return "your recent session"
    return str(ts)[:10]


def _solutions_from_response(resp: Optional[dict]) -> list[dict]:
    if not isinstance(resp, dict):
        return []
    sols = resp.get("solutions")
    return sols if isinstance(sols, list) else []


def _primary_cause(resp: Optional[dict]) -> Optional[str]:
    if isinstance(resp, dict):
        d = resp.get("diagnosis")
        if isinstance(d, dict):
            return d.get("primary_cause")
    return None


_SHELL_OPEN = (
    '<div style="font-family:-apple-system,Segoe UI,Roboto,Arial,sans-serif;'
    'max-width:560px;margin:0 auto;color:#1A1A1A;font-size:14px;line-height:1.55">'
    '<div style="border-bottom:2px solid #D69D3F;padding-bottom:10px;margin-bottom:18px">'
    '<span style="font-size:20px;font-weight:700;letter-spacing:1px;color:#1A1A1A">AKARI</span>'
    '<span style="color:#6B7280;font-size:12px;margin-left:8px">Projector diagnostic support</span>'
    "</div>"
)


def _shell_close(base: str) -> str:
    return (
        f'<div style="margin-top:22px;padding-top:14px;border-top:1px solid #E5E7EB;'
        f'font-size:11px;color:#6B7280;line-height:1.5">{_esc(DISCLAIMER_TEXT)}</div>'
        f'<div style="margin-top:12px;font-size:11px;color:#9CA3AF">'
        f"Internal tool. You are receiving this "
        f"because you ran a diagnosis on AKARI.</div></div>"
    )


def confirmation_email(*, diagnosis_id: str, diagnosis_response: Optional[dict],
                       problem_text: Optional[str], diagnosis_ts: Optional[str],
                       worked: Optional[bool]) -> tuple[str, str, str]:
    """E1: sent right after feedback is submitted. Summary + receipt + add-more."""
    base = base_url()
    link = f"{base}/feedback/{diagnosis_id}"
    cause = _primary_cause(diagnosis_response)
    sols = _solutions_from_response(diagnosis_response)
    outcome = (
        "you reported it <strong>resolved the issue</strong>"
        if worked is True else
        "you reported it <strong>did not resolve the issue</strong>"
        if worked is False else
        "you submitted feedback"
    )

    sol_html = ""
    for s in sols[:3]:
        if isinstance(s, dict) and s.get("action"):
            sol_html += (
                f'<li style="margin-bottom:6px">{_esc(s.get("action"))}</li>'
            )
    sol_block = (
        f'<div style="margin:14px 0"><div style="font-weight:600;margin-bottom:6px">'
        f"Recommended steps</div><ol style=\"margin:0;padding-left:18px\">{sol_html}</ol></div>"
        if sol_html else ""
    )

    subject = "AKARI - thanks for your feedback"
    html = (
        _SHELL_OPEN +
        '<p style="margin:0 0 14px">Thank you. Your feedback has been recorded and '
        f"{outcome}.</p>" +
        '<div style="background:#FAFBFC;border:1px solid #E5E7EB;border-radius:8px;padding:14px;margin-bottom:8px">' +
        f'<div style="font-size:12px;color:#6B7280;margin-bottom:6px">Diagnosis from {_esc(_short_date(diagnosis_ts))}</div>' +
        (f'<div style="margin-bottom:8px"><strong>Your report:</strong> {_esc((problem_text or "")[:300])}</div>' if problem_text else "") +
        (f'<div style="margin-bottom:4px"><strong>Likely cause:</strong> {_esc(cause)}</div>' if cause else "") +
        sol_block +
        "</div>" +
        '<p style="margin:16px 0 6px">Your original feedback is on file and will not be '
        "changed. If anything develops with this case, you can <strong>add an update</strong> "
        "at any time (your first note stays intact):</p>" +
        f'<p style="margin:6px 0 0"><a href="{_esc(link)}" '
        'style="display:inline-block;background:#10218B;color:#fff;text-decoration:none;'
        'padding:10px 20px;border-radius:6px;font-weight:600">Add an update</a></p>' +
        _shell_close(base)
    )
    text = (
        f"AKARI - thanks for your feedback\n\n"
        f"Your feedback has been recorded ({'resolved' if worked else 'not resolved' if worked is False else 'submitted'}).\n"
        f"Diagnosis from {_short_date(diagnosis_ts)}.\n"
        + (f"Your report: {(problem_text or '')[:300]}\n" if problem_text else "")
        + (f"Likely cause: {cause}\n" if cause else "")
        + f"\nYour original feedback stays on file unchanged. Add an update any time:\n{link}\n\n"
        + DISCLAIMER_TEXT + "\n"
    )
    return subject, html, text


def update_receipt_email(*, diagnosis_id: str, update_text: str,
                         diagnosis_ts: Optional[str]) -> tuple[str, str, str]:
    """Sent when a user appends an additional update to existing feedback."""
    base = base_url()
    link = f"{base}/feedback/{diagnosis_id}"
    subject = "AKARI - your feedback update was added"
    html = (
        _SHELL_OPEN +
        '<p style="margin:0 0 14px">Your additional update has been added to this '
        "case. Your earlier feedback remains on file unchanged.</p>" +
        '<div style="background:#FAFBFC;border:1px solid #E5E7EB;border-radius:8px;padding:14px;margin-bottom:8px">' +
        f'<div style="font-size:12px;color:#6B7280;margin-bottom:6px">Diagnosis from {_esc(_short_date(diagnosis_ts))}</div>' +
        f'<div><strong>You added:</strong> {_esc(update_text[:600])}</div>' +
        "</div>" +
        f'<p style="margin:16px 0 0"><a href="{_esc(link)}" '
        'style="display:inline-block;background:#10218B;color:#fff;text-decoration:none;'
        'padding:10px 20px;border-radius:6px;font-weight:600">View this case</a></p>' +
        _shell_close(base)
    )
    text = (
        f"AKARI - your feedback update was added\n\n"
        f"Your additional update has been added; earlier feedback is unchanged.\n"
        f"You added: {update_text[:600]}\n\nView: {link}\n\n" + DISCLAIMER_TEXT + "\n"
    )
    return subject, html, text


def nudge_email(*, diagnosis_id: str, problem_text: Optional[str],
                diagnosis_ts: Optional[str]) -> tuple[str, str, str]:
    """E2: sent 24h after a diagnosis that got no feedback."""
    base = base_url()
    link = f"{base}/feedback/{diagnosis_id}"
    subject = "AKARI - did the recommendation work?"
    html = (
        _SHELL_OPEN +
        f'<p style="margin:0 0 14px">You ran a diagnosis on AKARI on '
        f"{_esc(_short_date(diagnosis_ts))}. Did the recommendation help resolve the issue?</p>" +
        (f'<div style="background:#FAFBFC;border:1px solid #E5E7EB;border-radius:8px;'
         f'padding:14px;margin-bottom:8px"><strong>Your report:</strong> '
         f'{_esc((problem_text or "")[:300])}</div>' if problem_text else "") +
        '<p style="margin:14px 0 6px">A few seconds of feedback makes the next '
        "diagnosis sharper for the whole team.</p>" +
        f'<p style="margin:6px 0 0"><a href="{_esc(link)}" '
        'style="display:inline-block;background:#10218B;color:#fff;text-decoration:none;'
        'padding:10px 20px;border-radius:6px;font-weight:600">Share feedback</a></p>' +
        _shell_close(base)
    )
    text = (
        f"AKARI - did the recommendation work?\n\n"
        f"You ran a diagnosis on {_short_date(diagnosis_ts)}.\n"
        + (f"Your report: {(problem_text or '')[:300]}\n" if problem_text else "")
        + f"\nShare feedback: {link}\n\n" + DISCLAIMER_TEXT + "\n"
    )
    return subject, html, text
